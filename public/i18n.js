// Global Translation Helper
function t(key, lang) {
  const current = lang || (window.state ? window.state.currentLang : 'fil') || 'fil';
  if (translations[current] && translations[current][key] !== undefined) {
    return translations[current][key];
  }
  // Fallback to Filipino then English
  return (translations.fil && translations.fil[key]) || (translations.en && translations.en[key]) || key;
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { translations, t };
}
